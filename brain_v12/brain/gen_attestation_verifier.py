"""Verify a signed, nonce-bound GEN hardware attestation.

This is an offline verifier: it performs no discovery or network I/O. The trust
anchor must be provisioned out-of-band by an operator and must belong to the
device/provider attestation issuer. A valid signature proves issuer provenance,
not that the issuer itself is honest or that mining revenue exists.
"""
from __future__ import annotations

import base64
import json
import math
import time
from typing import Any, Mapping

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

SCHEMA = "brain.gen-physical-attestation.v1"
AUDIENCE = "brain-gen-physical-proof"
MAX_VALIDITY_SECONDS = 300
REQUIRED_FIELDS = frozenset({
    "schema", "audience", "issuer_id", "subject_type", "subject_id",
    "evidence_id", "operation", "nonce", "result_digest",
    "identity_verified", "physical_presence_verified",
    "network_connection_verified", "device_diagnostic_passed",
    "issued_at", "expires_at", "signature",
})


def signing_payload(document: Mapping[str, Any]) -> bytes:
    """Canonical signed bytes; signature itself is excluded."""
    return json.dumps(
        {key: value for key, value in document.items() if key != "signature"},
        sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False,
    ).encode("utf-8")


def verify_gen_attestation(
    document: Mapping[str, Any],
    *,
    public_key_b64: str,
    expected_nonce: str,
    expected_subject_id: str,
    expected_subject_type: str,
    expected_operation: str,
    now: float | None = None,
) -> dict[str, Any]:
    """Verify signature, freshness, exact challenge/scope and device diagnostics.

    The expected nonce must be freshly generated by Brain and retained by the
    caller; never take it from the attestation being verified.
    """
    if not isinstance(public_key_b64, str) or not public_key_b64:
        raise ValueError("GEN_TRUST_ANCHOR_REQUIRED")
    if not isinstance(document, Mapping):
        raise ValueError("GEN_ATTESTATION_INVALID")
    doc = dict(document)
    if not REQUIRED_FIELDS.issubset(doc):
        raise ValueError("GEN_ATTESTATION_FIELDS_REQUIRED")
    if doc["schema"] != SCHEMA:
        raise ValueError("GEN_ATTESTATION_SCHEMA_INVALID")
    if doc["audience"] != AUDIENCE:
        raise ValueError("GEN_ATTESTATION_AUDIENCE_MISMATCH")
    if doc["subject_type"] not in {"ASIC_DEVICE", "HOSTED_ASIC"}:
        raise ValueError("GEN_ATTESTATION_SUBJECT_TYPE_INVALID")
    for field in ("issuer_id", "subject_id", "evidence_id", "operation", "nonce", "result_digest"):
        if not isinstance(doc[field], str) or not doc[field].strip():
            raise ValueError("GEN_ATTESTATION_FIELD_INVALID:" + field)
    if doc["subject_id"] != expected_subject_id or doc["subject_type"] != expected_subject_type:
        raise ValueError("GEN_ATTESTATION_SUBJECT_MISMATCH")
    if doc["operation"] != expected_operation:
        raise ValueError("GEN_ATTESTATION_OPERATION_MISMATCH")
    if not isinstance(expected_nonce, str) or len(expected_nonce) < 16:
        raise ValueError("GEN_EXPECTED_NONCE_INVALID")
    if doc["nonce"] != expected_nonce:
        raise ValueError("GEN_ATTESTATION_NONCE_MISMATCH")
    for field in ("identity_verified", "physical_presence_verified",
                  "network_connection_verified", "device_diagnostic_passed"):
        if doc[field] is not True:
            raise ValueError("GEN_ATTESTATION_CHECK_FAILED:" + field)
    issued, expires = doc["issued_at"], doc["expires_at"]
    if (isinstance(issued, bool) or not isinstance(issued, (int, float))
            or isinstance(expires, bool) or not isinstance(expires, (int, float))):
        raise ValueError("GEN_ATTESTATION_TIME_INVALID")
    current = time.time() if now is None else float(now)
    if not all(math.isfinite(float(x)) for x in (issued, expires, current)):
        raise ValueError("GEN_ATTESTATION_TIME_INVALID")
    if issued > current + 30:
        raise ValueError("GEN_ATTESTATION_NOT_YET_VALID")
    if expires <= current:
        raise ValueError("GEN_ATTESTATION_EXPIRED")
    if expires <= issued or expires - issued > MAX_VALIDITY_SECONDS or expires - current > MAX_VALIDITY_SECONDS:
        raise ValueError("GEN_ATTESTATION_VALIDITY_INVALID")
    try:
        key_bytes = base64.b64decode(public_key_b64, validate=True)
        signature = base64.b64decode(doc["signature"], validate=True)
        key = Ed25519PublicKey.from_public_bytes(key_bytes)
        key.verify(signature, signing_payload(doc))
    except (ValueError, TypeError, InvalidSignature) as exc:
        raise ValueError("GEN_ATTESTATION_SIGNATURE_INVALID") from exc

    # Return a verified statement only; caller must still keep replay prevention
    # state and the real device/provider trust-anchor enrollment outside this module.
    return {
        "verified": True,
        "issuer_id": doc["issuer_id"],
        "subject_type": doc["subject_type"],
        "subject_id": doc["subject_id"],
        "evidence_id": doc["evidence_id"],
        "operation": doc["operation"],
        "nonce": doc["nonce"],
        "result_digest": doc["result_digest"],
        "issued_at": float(issued),
        "expires_at": float(expires),
        "signature_algorithm": "Ed25519",
    }


__all__ = ["AUDIENCE", "MAX_VALIDITY_SECONDS", "SCHEMA", "signing_payload", "verify_gen_attestation"]
